'use strict';
const assert=require('node:assert/strict');
const {createLedger}=require('./orka-club-ledger-preview.cjs');
const l=createLedger();
const base={accountId:'customer-1',orderId:'order-1',eligibleSubtotalPiastres:100000,deliveredAt:'2026-11-01T00:00:00Z'};
assert.equal(l.delivered(base).amount,10000);
assert.equal(l.delivered(base).duplicate,true);
assert.equal(l.snapshot('customer-1').length,1);
assert.equal(l.snapshot('customer-2').length,0);
const first=l.spend({accountId:'customer-1',redemptionId:'checkout-1',itemPricePiastres:8000,now:'2026-11-02T00:00:00Z'});
assert.equal(first.discount,8000);
assert.equal(l.snapshot('customer-1')[0].remaining,2000);
assert.equal(l.spend({accountId:'customer-1',redemptionId:'checkout-1',itemPricePiastres:8000,now:'2026-11-02T00:00:00Z'}).duplicate,true);
assert.equal(l.snapshot('customer-1')[0].remaining,2000);
assert.equal(l.spend({accountId:'customer-1',redemptionId:'checkout-2',itemPricePiastres:8000,now:'2026-11-02T00:00:00Z'}).discount,2000);
assert.equal(l.delivered({...base,orderId:'order-2',usedWallet:true}).amount,0);
assert.equal(l.snapshot('customer-1').length,1);
assert.throws(()=>l.snapshot(''));
console.log('Preview-only ledger sequential idempotency and isolation tests passed');
